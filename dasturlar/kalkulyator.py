# --- qadam 1: a + b yigindisi ---
a = 12
b = 5
print("Yigindi:", a + b)

# --- qadam 2: ayirma qoshildi ---
print("Ayirma:", a - b)

# --- qadam 3: kopaytma qoshildi ---
print("Kopaytma:", a * b)

# --- qadam 4: bolish (nolga tekshiruv bilan) ---
if b != 0:
    print("Bolinma:", a / b)
else:
    print("Nolga bolib bolmaydi")

# --- qadam 5: darajaga oshirish ---
print("Daraja:", a ** b)
